            f'<article class="product{wide} tilt3d">'
            f'<img class="tilt3d__inner" src="assets/img/{img}" alt="{plain}" width="1200" height="1200" loading="lazy">'
            f'<a class="product__link" href="{ENQUIRY_HREF}" aria-label="Enquire about {plain}"></a>'
