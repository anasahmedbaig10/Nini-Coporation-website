def build_seo(pages):
    """sitemap.xml + robots.txt. Update BASE to the real domain before deploying."""
    BASE = "https://www.ninicorporation.com"
    urls = ""
    for name in sorted(pages):
        if name == "404.html":
            continue
        loc = BASE + "/" + ("" if name == "index.html" else name)
        pri = "1.0" if name == "index.html" else "0.7"
        urls += f"  <url><loc>{loc}</loc><priority>{pri}</priority></url>\n"

    sitemap = f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n{urls}</urlset>\n'
    with open(os.path.join(OUT, "sitemap.xml"), "w", encoding="utf-8") as f:
        f.write(sitemap)

    robots = f"User-agent: *\nAllow: /\n\nSitemap: {BASE}/sitemap.xml\n"
    with open(os.path.join(OUT, "robots.txt"), "w", encoding="utf-8") as f:
        f.write(robots)

    return len(sitemap), len(robots)


