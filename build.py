def nav_html(current):
    out = ['<nav class="nav" id="nav" aria-label="Primary">']
    for i, (label, href, subs) in enumerate(NAV):
        if subs:
            ddid = "dd-" + label.lower()
            active = " is-active" if any(current == s[2] for s in subs) else ""
            out.append('<div class="nav__item" data-dropdown>')
            out.append(f'<button class="nav__link{active}" type="button" aria-expanded="false" aria-controls="{ddid}">{label}{CHEV}</button>')
            out.append(f'<div class="dropdown" id="{ddid}"><ul class="dropdown__links">')
            for num, text, url in subs:
                out.append(f'<li><a href="{url}"><span class="num">{num}</span> {text}</a></li>')
            img, cap = PROMO[label]
            out.append('</ul>')
            out.append(f'<span class="dropdown__promo"><img src="{img}" alt="" width="1920" height="1072" loading="lazy"><span>{cap}</span></span>')
            out.append('</div></div>')
        else:
            active = " is-active" if current == href else ""
            out.append(f'<div class="nav__item"><a class="nav__link{active}" href="{href}">{label}</a></div>')
    out.append('<a class="pill nav__cta" href="contact.html#quote" style="display:none">Get a Quote</a>')
    out.append('</nav>')
    return "\n".join(out)


